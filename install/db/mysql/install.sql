CREATE TABLE IF NOT EXISTS b_onetrace_queue (
    ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
    SITE_ID CHAR(2) NOT NULL,
    KIND VARCHAR(16) NOT NULL,
    ITEM_KEY VARCHAR(64) NOT NULL DEFAULT '',
    PAYLOAD MEDIUMTEXT NOT NULL,
    ATTEMPTS SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    AVAILABLE_AT DATETIME NOT NULL,
    LAST_ERROR TEXT NULL,
    CREATED_AT DATETIME NOT NULL,
    PRIMARY KEY (ID),
    KEY IX_ONETRACE_QUEUE_DUE (SITE_ID, KIND, AVAILABLE_AT),
    KEY IX_ONETRACE_QUEUE_ITEM (SITE_ID, ITEM_KEY)
);

CREATE TABLE IF NOT EXISTS b_onetrace_order (
    ORDER_ID INT UNSIGNED NOT NULL,
    ANONYMOUS_ID VARCHAR(255) NOT NULL,
    PRIMARY KEY (ORDER_ID)
);

CREATE TABLE IF NOT EXISTS b_onetrace_loyalty (
    ORDER_ID INT UNSIGNED NOT NULL,
    SITE_ID CHAR(2) NOT NULL,
    REDEMPTION VARCHAR(64) NOT NULL,
    POINTS INT UNSIGNED NOT NULL,
    DISCOUNT DECIMAL(18,4) NOT NULL,
    CONFIRMED_AT DATETIME NULL,
    CREATED_AT DATETIME NOT NULL,
    PRIMARY KEY (ORDER_ID),
    KEY IX_ONETRACE_LOYALTY_PENDING (CONFIRMED_AT, CREATED_AT)
);
